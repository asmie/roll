TEST(blake2b, multi_block_input)
{
	// Feed > 128 bytes (one BLAKE2b block) so update()'s multi-block path runs.
	BLAKE2b hash;
	std::vector<uint8_t> input(256);
	for (size_t i = 0; i < input.size(); ++i)
		input[i] = static_cast<uint8_t>(i);

	uint8_t out[64];
	hash.hash(out, input.data(), input.size());

	// Hash a second time to confirm determinism.
	uint8_t out2[64];
	hash.hash(out2, input.data(), input.size());
	for (int i = 0; i < 64; i++)
		ASSERT_EQ(out[i], out2[i]);
}
